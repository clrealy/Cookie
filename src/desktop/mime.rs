//! Registering `application/x-cookie-package` with the desktop.
//!
//! Two separate things have to happen for a double-click to work:
//!
//! 1. The system has to *recognise* a `.cpk` as a cookie — that is the
//!    shared-mime-info XML in this module.
//! 2. The system has to know *what opens one* — that is the default
//!    application entry in `mimeapps.list`.
//!
//! Neither needs root; both live under the user's data and config
//! directories.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::cpk;
use crate::paths;

/// Filename of our shared-mime-info package.
pub const MIME_PACKAGE_FILE: &str = "cookie.xml";

/// The shared-mime-info definition for `.cpk`.
///
/// Note what is **not** here: a `<glob pattern="*.cpk"/>`.
///
/// `.cpk` is not ours alone — several games use the extension for unrelated
/// archive formats. With a glob present, shared-mime-info matches on the name
/// and never consults magic, so *any* file called `.cpk` would be claimed as
/// a cookie, given Cookie's icon, and handed to `cookie eat` on a
/// double-click. Raising the magic priority does not change that; the glob
/// wins either way. This was measured, not assumed.
///
/// So detection is by content alone: magic that looks for the literal
/// `manifest.toml` at offset 30, which is where a zip's first local file
/// header puts its filename. That is why `cookie bake` writes
/// `manifest.toml` as the first entry.
///
/// What this buys:
///
/// - someone else's `.cpk` is correctly left alone;
/// - a cookie is recognised even with no extension at all.
///
/// What it costs: a cookie whose contents cannot be read — on a remote share,
/// say, or still downloading — is not recognised by its name alone. That is
/// the better trade: failing to claim our own file is a small annoyance,
/// while claiming someone else's is a broken double-click on their data.
///
/// Priority 60 puts the magic above `application/zip`'s own 50, so a cookie
/// is reported as a cookie rather than as a zip.
pub fn mime_xml() -> String {
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by cookie {version}. Do not edit; run `cookie kitchen setup`. -->
<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">
  <mime-type type="{mime}">
    <comment>Cookie package</comment>
    <comment xml:lang="en">Cookie package</comment>
    <generic-icon name="package-x-generic"/>
    <icon name="application-x-cookie-package"/>
    <sub-class-of type="application/zip"/>
    <magic priority="60">
      <match type="string" value="PK\003\004" offset="0">
        <match type="string" value="manifest.toml" offset="30"/>
      </match>
    </magic>
  </mime-type>
</mime-info>
"#,
        version = env!("CARGO_PKG_VERSION"),
        mime = cpk::MIME_TYPE,
    )
}

/// Write the MIME package file. Returns the path written.
pub fn install(mime_packages: &Path) -> Result<std::path::PathBuf> {
    paths::ensure_dir(mime_packages)?;
    let path = mime_packages.join(MIME_PACKAGE_FILE);
    fs::write(&path, mime_xml()).with_context(|| format!("cannot write {}", path.display()))?;
    Ok(path)
}

/// Remove the MIME package file.
pub fn remove(mime_packages: &Path) -> Result<bool> {
    let path = mime_packages.join(MIME_PACKAGE_FILE);
    if !path.exists() {
        return Ok(false);
    }
    fs::remove_file(&path).with_context(|| format!("cannot remove {}", path.display()))?;
    Ok(true)
}

/// Make `desktop_id` the default application for `mime_type`.
///
/// This edits `mimeapps.list` directly rather than shelling out to
/// `xdg-mime`, which belongs to the optional `xdg-utils` package and is not
/// installed everywhere. Other entries in the file are preserved exactly;
/// only the one key changes.
pub fn set_default_application(mimeapps: &Path, mime_type: &str, desktop_id: &str) -> Result<()> {
    let existing = fs::read_to_string(mimeapps).unwrap_or_default();
    let updated = with_default_application(&existing, mime_type, desktop_id);

    if let Some(parent) = mimeapps.parent() {
        paths::ensure_dir(parent)?;
    }
    fs::write(mimeapps, updated).with_context(|| format!("cannot write {}", mimeapps.display()))?;
    Ok(())
}

/// Remove our default-application entry, leaving everything else alone.
pub fn clear_default_application(mimeapps: &Path, mime_type: &str) -> Result<()> {
    if !mimeapps.exists() {
        return Ok(());
    }
    let existing = fs::read_to_string(mimeapps)
        .with_context(|| format!("cannot read {}", mimeapps.display()))?;
    let updated = without_default_application(&existing, mime_type);
    fs::write(mimeapps, updated).with_context(|| format!("cannot write {}", mimeapps.display()))?;
    Ok(())
}

/// Which desktop file is currently registered for a MIME type, if any.
pub fn default_application(mimeapps: &Path, mime_type: &str) -> Option<String> {
    let text = fs::read_to_string(mimeapps).ok()?;
    let mut in_group = false;
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            in_group = trimmed == "[Default Applications]";
            continue;
        }
        if !in_group {
            continue;
        }
        if let Some((key, value)) = trimmed.split_once('=') {
            if key.trim() == mime_type {
                return Some(value.trim().to_string());
            }
        }
    }
    None
}

/// Pure-text version of [`set_default_application`], so the editing rules are
/// testable without touching a filesystem.
fn with_default_application(existing: &str, mime_type: &str, desktop_id: &str) -> String {
    let entry = format!("{mime_type}={desktop_id}");
    let mut out: Vec<String> = Vec::new();
    let mut in_group = false;
    let mut wrote = false;
    let mut saw_group = false;

    for line in existing.lines() {
        let trimmed = line.trim();

        if trimmed.starts_with('[') {
            // Leaving our group without having written the key? Write it now,
            // before the next group starts.
            if in_group && !wrote {
                out.push(entry.clone());
                wrote = true;
            }
            in_group = trimmed == "[Default Applications]";
            saw_group |= in_group;
            out.push(line.to_string());
            continue;
        }

        if in_group {
            if let Some((key, _)) = trimmed.split_once('=') {
                if key.trim() == mime_type {
                    // Replace in place, keeping its position in the file.
                    if !wrote {
                        out.push(entry.clone());
                        wrote = true;
                    }
                    continue;
                }
            }
        }
        out.push(line.to_string());
    }

    if in_group && !wrote {
        out.push(entry.clone());
        wrote = true;
    }
    if !saw_group {
        if !out.is_empty() && !out.last().map(|l| l.trim().is_empty()).unwrap_or(false) {
            out.push(String::new());
        }
        out.push("[Default Applications]".to_string());
        out.push(entry);
    } else if !wrote {
        out.push(entry);
    }

    let mut text = out.join("\n");
    if !text.ends_with('\n') {
        text.push('\n');
    }
    text
}

/// Pure-text version of [`clear_default_application`].
fn without_default_application(existing: &str, mime_type: &str) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut in_group = false;

    for line in existing.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            in_group = trimmed == "[Default Applications]";
            out.push(line.to_string());
            continue;
        }
        if in_group {
            if let Some((key, _)) = trimmed.split_once('=') {
                if key.trim() == mime_type {
                    continue;
                }
            }
        }
        out.push(line.to_string());
    }

    let mut text = out.join("\n");
    if !text.is_empty() && !text.ends_with('\n') {
        text.push('\n');
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths::ScratchDir;

    const MIME: &str = "application/x-cookie-package";

    #[test]
    fn the_xml_identifies_a_cookie_by_content() {
        let xml = mime_xml();
        assert!(
            xml.contains(r#"type="application/x-cookie-package""#),
            "{xml}"
        );
        assert!(
            xml.contains(r#"value="manifest.toml" offset="30""#),
            "{xml}"
        );
        assert!(
            xml.contains(r#"<sub-class-of type="application/zip"/>"#),
            "{xml}"
        );
        assert!(xml.starts_with("<?xml"), "{xml}");
    }

    /// Regression test for a measured bug.
    ///
    /// With a glob present, an unrelated zip named `something.cpk` was
    /// reported as `application/x-cookie-package`: shared-mime-info matched
    /// the name and never looked at the content. Raising the magic priority
    /// did not help. Detection has to be by content alone.
    #[test]
    fn there_is_no_glob_claiming_every_cpk_file() {
        let xml = mime_xml();
        assert!(
            !xml.contains("<glob"),
            "a glob would claim other people's .cpk files:\n{xml}"
        );
    }

    #[test]
    fn the_magic_priority_beats_plain_zip() {
        // application/zip itself registers at priority 50.
        assert!(mime_xml().contains(r#"<magic priority="60">"#));
    }

    #[test]
    fn install_and_remove_round_trip() {
        let scratch = ScratchDir::new("mime").expect("scratch");
        let packages = scratch.path().join("mime/packages");

        let path = install(&packages).expect("install");
        assert!(path.is_file());
        assert_eq!(
            path.file_name().and_then(|n| n.to_str()),
            Some("cookie.xml")
        );

        assert!(remove(&packages).expect("remove"));
        assert!(!path.exists());
        assert!(!remove(&packages).expect("remove again"), "already gone");
    }

    #[test]
    fn writes_the_group_when_the_file_is_empty() {
        let text = with_default_application("", MIME, "cookie.desktop");
        assert!(text.contains("[Default Applications]"));
        assert!(text.contains("application/x-cookie-package=cookie.desktop"));
        assert!(text.ends_with('\n'));
    }

    #[test]
    fn adds_to_an_existing_group_without_touching_other_entries() {
        let existing = "[Default Applications]\n\
                        text/plain=org.kde.kwrite.desktop\n\
                        image/png=org.kde.gwenview.desktop\n";
        let text = with_default_application(existing, MIME, "cookie.desktop");
        assert!(text.contains("text/plain=org.kde.kwrite.desktop"), "{text}");
        assert!(
            text.contains("image/png=org.kde.gwenview.desktop"),
            "{text}"
        );
        assert!(
            text.contains("application/x-cookie-package=cookie.desktop"),
            "{text}"
        );
        assert_eq!(text.matches("[Default Applications]").count(), 1, "{text}");
    }

    #[test]
    fn replaces_an_existing_entry_in_place() {
        let existing = "[Default Applications]\n\
                        application/x-cookie-package=something-else.desktop\n\
                        text/plain=kwrite.desktop\n";
        let text = with_default_application(existing, MIME, "cookie.desktop");
        assert!(!text.contains("something-else"), "{text}");
        assert_eq!(
            text.matches("application/x-cookie-package=").count(),
            1,
            "{text}"
        );
        assert!(text.contains("text/plain=kwrite.desktop"), "{text}");
    }

    #[test]
    fn leaves_other_groups_alone() {
        let existing = "[Added Associations]\n\
                        text/plain=kwrite.desktop;\n\
                        \n\
                        [Default Applications]\n\
                        text/html=firefox.desktop\n";
        let text = with_default_application(existing, MIME, "cookie.desktop");
        assert!(text.contains("[Added Associations]"), "{text}");
        assert!(text.contains("text/plain=kwrite.desktop;"), "{text}");
        assert!(text.contains("text/html=firefox.desktop"), "{text}");

        // And our key landed in the right group, not the first one.
        let default_group = text
            .split("[Default Applications]")
            .nth(1)
            .unwrap_or_default();
        assert!(
            default_group.contains("application/x-cookie-package="),
            "{text}"
        );
    }

    #[test]
    fn a_group_that_comes_before_another_still_gets_the_key() {
        let existing = "[Default Applications]\n\
                        text/html=firefox.desktop\n\
                        \n\
                        [Added Associations]\n\
                        text/plain=kwrite.desktop;\n";
        let text = with_default_application(existing, MIME, "cookie.desktop");
        let before_added = text
            .split("[Added Associations]")
            .next()
            .unwrap_or_default();
        assert!(
            before_added.contains("application/x-cookie-package=cookie.desktop"),
            "the key must land inside [Default Applications]:\n{text}"
        );
    }

    #[test]
    fn appends_the_group_when_the_file_has_others_only() {
        let existing = "[Added Associations]\ntext/plain=kwrite.desktop;\n";
        let text = with_default_application(existing, MIME, "cookie.desktop");
        assert!(text.contains("[Added Associations]"), "{text}");
        assert!(text.contains("[Default Applications]"), "{text}");
        assert!(
            text.contains("application/x-cookie-package=cookie.desktop"),
            "{text}"
        );
    }

    #[test]
    fn clearing_removes_only_our_key() {
        let existing = "[Default Applications]\n\
                        application/x-cookie-package=cookie.desktop\n\
                        text/plain=kwrite.desktop\n";
        let text = without_default_application(existing, MIME);
        assert!(!text.contains("x-cookie-package"), "{text}");
        assert!(text.contains("text/plain=kwrite.desktop"), "{text}");
        assert!(text.contains("[Default Applications]"), "{text}");
    }

    #[test]
    fn reading_back_what_was_written() {
        let scratch = ScratchDir::new("mimeapps").expect("scratch");
        let file = scratch.path().join("mimeapps.list");

        assert_eq!(default_application(&file, MIME), None);

        set_default_application(&file, MIME, "cookie.desktop").expect("set");
        assert_eq!(
            default_application(&file, MIME).as_deref(),
            Some("cookie.desktop")
        );

        clear_default_application(&file, MIME).expect("clear");
        assert_eq!(default_application(&file, MIME), None);
    }

    #[test]
    fn a_key_outside_the_default_group_is_not_read_as_ours() {
        let scratch = ScratchDir::new("mimeapps").expect("scratch");
        let file = scratch.path().join("mimeapps.list");
        fs::write(
            &file,
            "[Added Associations]\napplication/x-cookie-package=other.desktop;\n",
        )
        .expect("write");
        assert_eq!(default_application(&file, MIME), None);
    }
}
