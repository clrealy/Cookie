//! Android properties, as a file the Android side reads at boot.
//!
//! Android's graphics stack is configured through properties: which gralloc
//! implementation to load, which EGL driver, what the display density is.
//! The host has to decide those, because only the host knows what hardware
//! is actually present — so Cookie computes them and writes them where the
//! Android side can read them.
//!
//! The format is the one Android uses everywhere: one `key=value` per line,
//! `#` for comments.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};

/// An ordered set of Android properties.
///
/// Sorted by key, so the generated file is stable: a rebuild that changes
/// nothing produces a byte-identical file, which makes it worth diffing.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(transparent)]
pub struct Properties {
    entries: BTreeMap<String, String>,
}

impl Properties {
    pub fn new() -> Self {
        Self::default()
    }

    /// Set a property, replacing any previous value.
    ///
    /// Rejects anything that could not survive the round trip through the
    /// file: a key must look like a property name, and neither key nor value
    /// may contain a newline. Values are partly derived from host paths, so
    /// this is the boundary that keeps a strange path from inventing a second
    /// property.
    pub fn set(&mut self, key: &str, value: &str) -> Result<()> {
        validate_key(key)?;
        validate_value(value)?;
        self.entries.insert(key.to_string(), value.to_string());
        Ok(())
    }

    /// Set a property, ignoring it if the value is empty.
    ///
    /// Android treats an empty property as unset but present, which is not
    /// the same as absent — `ro.hardware.gralloc=` would have it load nothing
    /// rather than fall back.
    pub fn set_if_present(&mut self, key: &str, value: &str) -> Result<()> {
        if value.is_empty() {
            return Ok(());
        }
        self.set(key, value)
    }

    pub fn get(&self, key: &str) -> Option<&str> {
        self.entries.get(key).map(String::as_str)
    }

    pub fn remove(&mut self, key: &str) -> bool {
        self.entries.remove(key).is_some()
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn iter(&self) -> impl Iterator<Item = (&str, &str)> {
        self.entries.iter().map(|(k, v)| (k.as_str(), v.as_str()))
    }

    /// Merge another set over this one; the other side wins.
    pub fn merge(&mut self, other: &Properties) {
        for (key, value) in other.iter() {
            self.entries.insert(key.to_string(), value.to_string());
        }
    }

    /// Render the file.
    pub fn render(&self) -> String {
        let mut out = format!(
            "# Generated by cookie {}. Do not edit; run `cookie oven start`.\n\
             # Android reads these at boot to decide how to draw.\n\n",
            env!("CARGO_PKG_VERSION")
        );
        for (key, value) in self.iter() {
            out.push_str(key);
            out.push('=');
            out.push_str(value);
            out.push('\n');
        }
        out
    }

    /// Parse a property file. Unparseable lines are skipped, not fatal: this
    /// reads files a user may have edited.
    pub fn parse(text: &str) -> Self {
        let mut properties = Self::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            let (key, value) = (key.trim(), value.trim());
            // Reuse the same validation, so nothing gets in by being read
            // that could not have been written.
            let _ = properties.set(key, value);
        }
        properties
    }

    pub fn write(&self, path: &Path) -> Result<()> {
        if let Some(parent) = path.parent() {
            crate::paths::ensure_dir(parent)?;
        }
        fs::write(path, self.render()).with_context(|| format!("cannot write {}", path.display()))
    }

    pub fn read(path: &Path) -> Result<Self> {
        if !path.is_file() {
            return Ok(Self::new());
        }
        let text =
            fs::read_to_string(path).with_context(|| format!("cannot read {}", path.display()))?;
        Ok(Self::parse(&text))
    }
}

/// Android property names are dotted lowercase identifiers.
fn validate_key(key: &str) -> Result<()> {
    if key.is_empty() {
        bail!("a property name cannot be empty");
    }
    if key.len() > 92 {
        // Android's own PROP_NAME_MAX.
        bail!("the property name `{key}` is too long (Android allows 92 characters)");
    }
    if !key
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
    {
        bail!(
            "`{key}` is not a valid property name.\n\
             Names are letters, digits, dots, underscores and hyphens, such as \
             persist.cookie.multi_windows"
        );
    }
    Ok(())
}

fn validate_value(value: &str) -> Result<()> {
    if value.contains('\n') || value.contains('\r') {
        bail!("a property value cannot contain a line break");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths::ScratchDir;

    #[test]
    fn properties_render_sorted_and_stable() {
        let mut props = Properties::new();
        props.set("ro.z.last", "3").expect("set");
        props.set("ro.a.first", "1").expect("set");
        props.set("ro.m.middle", "2").expect("set");

        let rendered = props.render();
        let keys: Vec<&str> = rendered
            .lines()
            .filter(|l| !l.starts_with('#') && !l.is_empty())
            .filter_map(|l| l.split_once('=').map(|(k, _)| k))
            .collect();
        assert_eq!(keys, vec!["ro.a.first", "ro.m.middle", "ro.z.last"]);

        // Stable: same input, same bytes.
        assert_eq!(rendered, props.render());
    }

    #[test]
    fn round_trips_through_text() {
        let mut props = Properties::new();
        props.set("ro.hardware.gralloc", "gbm").expect("set");
        props.set("ro.hardware.egl", "mesa").expect("set");

        let parsed = Properties::parse(&props.render());
        assert_eq!(parsed, props);
    }

    #[test]
    fn parsing_skips_comments_and_junk() {
        let text = "# a comment\n\
                    \n\
                    ro.good=yes\n\
                    this line has no equals sign\n\
                    ro.also.good = spaced \n";
        let props = Properties::parse(text);
        assert_eq!(props.len(), 2);
        assert_eq!(props.get("ro.good"), Some("yes"));
        assert_eq!(props.get("ro.also.good"), Some("spaced"));
    }

    /// A value derived from a host path must not be able to invent a second
    /// property by carrying a newline.
    #[test]
    fn a_newline_in_a_value_is_refused() {
        let mut props = Properties::new();
        let err = props
            .set("ro.hardware.gralloc", "gbm\nro.secure=0")
            .unwrap_err()
            .to_string();
        assert!(err.contains("line break"), "{err}");
        assert!(props.is_empty(), "nothing should have been stored");
    }

    #[test]
    fn a_newline_cannot_sneak_in_through_parsing_either() {
        // Parsing splits on lines, so this is really a check that a crafted
        // file cannot produce a value containing one.
        let props = Properties::parse("ro.a=1\nro.secure=0\n");
        assert_eq!(props.get("ro.a"), Some("1"));
        assert!(!props.get("ro.a").unwrap_or_default().contains('\n'));
    }

    #[test]
    fn invalid_property_names_are_refused() {
        let mut props = Properties::new();
        for bad in ["", "has space", "has=equals", "has\nnewline", "has/slash"] {
            assert!(props.set(bad, "x").is_err(), "{bad:?} should be refused");
        }
        assert!(props.set(&"a".repeat(93), "x").is_err(), "too long");
        assert!(props.set(&"a".repeat(92), "x").is_ok(), "exactly the limit");
    }

    #[test]
    fn valid_names_are_accepted() {
        let mut props = Properties::new();
        for good in [
            "ro.hardware.gralloc",
            "persist.cookie.multi_windows",
            "ro.sf.lcd_density",
            "some-prop",
        ] {
            assert!(props.set(good, "x").is_ok(), "{good} should be accepted");
        }
    }

    #[test]
    fn an_empty_value_is_skipped_rather_than_written_blank() {
        // An empty property is "set but empty" to Android, which is not the
        // same as absent: it would load nothing instead of falling back.
        let mut props = Properties::new();
        props
            .set_if_present("ro.hardware.gralloc", "")
            .expect("set");
        assert!(props.is_empty());

        props
            .set_if_present("ro.hardware.gralloc", "gbm")
            .expect("set");
        assert_eq!(props.get("ro.hardware.gralloc"), Some("gbm"));
    }

    #[test]
    fn merging_lets_the_other_side_win() {
        let mut base = Properties::new();
        base.set("ro.a", "base").expect("set");
        base.set("ro.b", "base").expect("set");

        let mut over = Properties::new();
        over.set("ro.b", "over").expect("set");
        over.set("ro.c", "over").expect("set");

        base.merge(&over);
        assert_eq!(base.get("ro.a"), Some("base"));
        assert_eq!(base.get("ro.b"), Some("over"));
        assert_eq!(base.get("ro.c"), Some("over"));
    }

    #[test]
    fn files_round_trip() {
        let scratch = ScratchDir::new("props").expect("scratch");
        let path = scratch.path().join("sub/cookie.prop");

        let mut props = Properties::new();
        props.set("ro.hardware.gralloc", "gbm").expect("set");
        props.write(&path).expect("write");

        assert!(path.is_file());
        assert_eq!(Properties::read(&path).expect("read"), props);
    }

    #[test]
    fn reading_a_file_that_is_not_there_is_empty_not_an_error() {
        let props = Properties::read(Path::new("/nope/missing.prop")).expect("read");
        assert!(props.is_empty());
    }

    #[test]
    fn removal_reports_whether_anything_went() {
        let mut props = Properties::new();
        props.set("ro.a", "1").expect("set");
        assert!(props.remove("ro.a"));
        assert!(!props.remove("ro.a"));
    }
}
