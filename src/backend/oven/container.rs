//! The container the Android system runs in.
//!
//! ## Why LXC
//!
//! The oven replaces **Waydroid**, not LXC. Waydroid is a whole session
//! manager — image handling, properties, window plumbing, its own daemon —
//! and that is the part Cookie wants to own, because it is the part that
//! decides how an app feels on the desktop.
//!
//! Running a container is not that part. LXC already does it, it is what
//! Waydroid itself uses, it is a plain binary with no init-system opinion so
//! it works the same on OpenRC and systemd, and writing our own namespace and
//! `pivot_root` plumbing would mean a lot of `unsafe` to arrive back where
//! LXC already is.
//!
//! So Cookie owns the image, binderfs, the configuration, the lifecycle and
//! the app commands. LXC is the engine underneath, and the config written
//! here is the whole of what Cookie asks of it.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use super::display::{CONTAINER_RUNTIME_DIR, CONTAINER_WAYLAND_DISPLAY};

/// Name of the container Cookie manages.
pub const CONTAINER_NAME: &str = "cookie";

/// Everything needed to write a container config.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ContainerConfig {
    /// Where the Android root filesystem is mounted on the host.
    pub rootfs: PathBuf,
    /// Writable overlay for the container's own state.
    pub data_dir: PathBuf,
    /// binderfs mount point, or `/dev` when using legacy devices.
    pub binder_path: PathBuf,
    /// Binder devices to expose.
    pub binder_devices: Vec<String>,
    /// GPU render nodes to pass through, if any.
    pub render_nodes: Vec<PathBuf>,
    /// The desktop's Wayland socket. The Android side's hardware composer
    /// connects to this from inside the container; it is how an app's window
    /// reaches the screen.
    pub wayland_socket: Option<PathBuf>,
    /// The desktop's PulseAudio or PipeWire socket, so apps can make a noise.
    #[serde(default)]
    pub pulse_socket: Option<PathBuf>,
    /// Whether this host uses the unified cgroup hierarchy. The device
    /// allowlist is spelled differently on each, and writing the wrong one
    /// means no allowlist at all.
    #[serde(default)]
    pub cgroup_v2: bool,
    /// Host EGL directories to expose, for a host that carries its own
    /// Android graphics libraries.
    #[serde(default)]
    pub host_egl_dirs: Vec<PathBuf>,
    /// Uid and gid the session belongs to.
    pub uid: u32,
    pub gid: u32,
}

impl ContainerConfig {
    /// Render the LXC configuration file.
    ///
    /// Written as one string rather than through a builder because that is
    /// what it is: a flat file whose exact contents matter, and which is far
    /// easier to review — and to test — when it reads the way it will land on
    /// disk.
    pub fn render(&self) -> String {
        let mut out = String::new();

        let _ = writeln!(
            out,
            "# Generated by cookie {}. Do not edit; run `cookie oven start`.\n\
             # This file configures the container Android runs in. Cookie owns\n\
             # everything above it; LXC just runs what is described here.\n",
            env!("CARGO_PKG_VERSION")
        );

        let _ = writeln!(out, "lxc.uts.name = {CONTAINER_NAME}");
        let _ = writeln!(out, "lxc.rootfs.path = dir:{}", self.rootfs.display());
        // Android's own init is the container's first process.
        let _ = writeln!(out, "lxc.init.cmd = /init");
        let _ = writeln!(out, "lxc.arch = {}", host_lxc_arch());
        let _ = writeln!(out, "lxc.console.path = none");
        out.push('\n');

        let _ = writeln!(out, "# Namespaces");
        // Sharing the network namespace keeps apps on the host's network,
        // which is what someone running a single app expects.
        let _ = writeln!(out, "lxc.namespace.keep = net");
        out.push('\n');

        // Android's init does a great deal that an ordinary container
        // process does not: it mounts filesystems, makes device nodes, sets
        // the clock and manages cgroups. LXC's default capability set drops
        // most of that, so the set it needs is named explicitly.
        let _ = writeln!(out, "# What Android's init needs to be allowed to do");
        let _ = writeln!(out, "lxc.cap.keep = {}", ANDROID_CAPABILITIES.join(" "));
        out.push('\n');

        let _ = writeln!(
            out,
            "# Android brings its own policy, so LXC's would only fight it"
        );
        let _ = writeln!(out, "lxc.apparmor.profile = unconfined");
        let _ = writeln!(out, "lxc.seccomp.profile =");
        out.push('\n');

        let _ = writeln!(out, "# Kernel filesystems");
        let _ = writeln!(out, "lxc.mount.auto = cgroup:ro sys:ro proc");
        // LXC's own /dev population is off because Android's ueventd does it;
        // the tmpfs below is what gives it somewhere to do it.
        let _ = writeln!(out, "lxc.autodev = 0");
        let _ = writeln!(
            out,
            "lxc.mount.entry = tmpfs dev tmpfs create=dir,mode=0755 0 0"
        );
        out.push('\n');

        let _ = writeln!(out, "# Devices: nothing is exposed that is not listed here");
        let prefix = if self.cgroup_v2 {
            "lxc.cgroup2"
        } else {
            "lxc.cgroup"
        };
        let _ = writeln!(out, "{prefix}.devices.deny = a");
        for device in STANDARD_DEVICES {
            let _ = writeln!(out, "{prefix}.devices.allow = {device}");
        }
        // With autodev off and a fresh tmpfs, these have to come from the
        // host or they are simply absent.
        for node in BASIC_DEV_NODES {
            let _ = writeln!(
                out,
                "lxc.mount.entry = /dev/{node} dev/{node} none bind,optional,create=file 0 0"
            );
        }
        out.push('\n');

        let _ = writeln!(out, "# Binder");
        for name in &self.binder_devices {
            let source = self.binder_path.join(name);
            let _ = writeln!(
                out,
                "lxc.mount.entry = {} dev/{name} none bind,optional,create=file 0 0",
                source.display()
            );
        }
        out.push('\n');

        if !self.render_nodes.is_empty() {
            let _ = writeln!(out, "# GPU");
            for node in &self.render_nodes {
                let name = node
                    .file_name()
                    .map(|n| n.to_string_lossy().into_owned())
                    .unwrap_or_default();
                let _ = writeln!(
                    out,
                    "lxc.mount.entry = {} dev/dri/{name} none bind,optional,create=file 0 0",
                    node.display()
                );
            }
            out.push('\n');
        }

        if !self.host_egl_dirs.is_empty() {
            let _ = writeln!(out, "# The host's own Android graphics libraries");
            for dir in &self.host_egl_dirs {
                let _ = writeln!(
                    out,
                    "lxc.mount.entry = {} {} none bind,optional,create=dir 0 0",
                    dir.display(),
                    dir.display().to_string().trim_start_matches('/')
                );
            }
            out.push('\n');
        }

        let _ = writeln!(out, "# Writable state");
        let _ = writeln!(
            out,
            "lxc.mount.entry = {} data none bind,create=dir 0 0",
            self.data_dir.display()
        );
        let _ = writeln!(out, "lxc.mount.entry = tmpfs dev/shm tmpfs defaults 0 0");
        out.push('\n');

        // This is the display bridge, such as it is on the host side. The
        // Wayland client is the hardware composer *inside* the image, so all
        // the host has to do is put the socket where that HAL looks for it.
        // The path is not arbitrary: it is the one a Waydroid-derived image
        // expects, so such an image works unmodified.
        if let Some(socket) = &self.wayland_socket {
            let _ = writeln!(
                out,
                "# Display: the desktop's Wayland socket, where Android looks for it"
            );
            // A tmpfs first, or there is nothing to mount the socket onto.
            let _ = writeln!(
                out,
                "lxc.mount.entry = tmpfs {} tmpfs create=dir,mode=0755 0 0",
                CONTAINER_RUNTIME_DIR.trim_start_matches('/')
            );
            let _ = writeln!(
                out,
                "lxc.mount.entry = {} {}/{} none rbind,create=file 0 0",
                socket.display(),
                CONTAINER_RUNTIME_DIR.trim_start_matches('/'),
                CONTAINER_WAYLAND_DISPLAY
            );
            // The HAL finds the socket through these, exactly as any other
            // Wayland client would.
            let _ = writeln!(
                out,
                "lxc.environment = XDG_RUNTIME_DIR={CONTAINER_RUNTIME_DIR}"
            );
            let _ = writeln!(
                out,
                "lxc.environment = WAYLAND_DISPLAY={CONTAINER_WAYLAND_DISPLAY}"
            );
            out.push('\n');
        }

        // The hardware composer needs this to fence its buffers.
        let _ = writeln!(out, "# Fencing, for the hardware composer");
        let _ = writeln!(
            out,
            "lxc.mount.entry = /dev/sw_sync dev/sw_sync none bind,optional,create=file 0 0"
        );
        out.push('\n');

        if let Some(socket) = &self.pulse_socket {
            let _ = writeln!(out, "# Sound");
            let _ = writeln!(
                out,
                "lxc.mount.entry = {} {}/pulse/native none bind,optional,create=file 0 0",
                socket.display(),
                CONTAINER_RUNTIME_DIR.trim_start_matches('/')
            );
            out.push('\n');
        }

        let _ = writeln!(out, "# Session owner");
        let _ = writeln!(out, "lxc.environment = COOKIE_UID={}", self.uid);
        let _ = writeln!(out, "lxc.environment = COOKIE_GID={}", self.gid);

        out
    }
}

/// What Android's init needs to be allowed to do.
///
/// `lxc.cap.keep` is an allowlist: everything not named here is dropped.
/// The set mirrors the one Waydroid's own container config keeps, because
/// these are what Android's init, ueventd and the HALs actually use.
const ANDROID_CAPABILITIES: &[&str] = &[
    "audit_control",
    "block_suspend",
    "chown",
    "dac_override",
    "dac_read_search",
    "fowner",
    "fsetid",
    "ipc_lock",
    "kill",
    "mknod",
    "net_admin",
    "net_bind_service",
    "net_raw",
    "setgid",
    "setpcap",
    "setuid",
    "sys_admin",
    "sys_chroot",
    "sys_nice",
    "sys_ptrace",
    "sys_resource",
    "sys_time",
    "syslog",
    "wake_alarm",
];

/// Device nodes that have to be bound in from the host, because `lxc.autodev`
/// is off and the `/dev` tmpfs starts empty.
const BASIC_DEV_NODES: &[&str] = &["null", "zero", "full", "random", "urandom", "tty", "ptmx"];

/// Does this host use the unified cgroup hierarchy?
pub fn host_uses_cgroup_v2() -> bool {
    // The unified hierarchy puts this file at the root; cgroup v1 has no
    // such file.
    Path::new("/sys/fs/cgroup/cgroup.controllers").exists()
}

/// Host directories carrying Android EGL libraries, if this is that sort of
/// host.
pub fn host_egl_dirs() -> Vec<PathBuf> {
    ["/vendor/lib/egl", "/vendor/lib64/egl"]
        .iter()
        .map(PathBuf::from)
        .filter(|p| p.is_dir())
        .collect()
}

/// Devices every Android container needs, in cgroup device-allowlist syntax.
const STANDARD_DEVICES: &[&str] = &[
    "c 1:3 rwm",   // /dev/null
    "c 1:5 rwm",   // /dev/zero
    "c 1:7 rwm",   // /dev/full
    "c 1:8 rwm",   // /dev/random
    "c 1:9 rwm",   // /dev/urandom
    "c 5:0 rwm",   // /dev/tty
    "c 5:2 rwm",   // /dev/ptmx
    "c 136:* rwm", // pseudoterminals
    "c 10:* rwm",  // misc, which is where binder lives
    "c 226:* rwm", // DRM
];

/// LXC's name for this architecture.
fn host_lxc_arch() -> &'static str {
    match std::env::consts::ARCH {
        "x86_64" => "x86_64",
        "x86" => "i686",
        "aarch64" => "aarch64",
        "arm" => "armv7l",
        other => other,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn config() -> ContainerConfig {
        ContainerConfig {
            rootfs: PathBuf::from("/home/u/.local/share/cookie/oven/rootfs"),
            data_dir: PathBuf::from("/home/u/.local/share/cookie/oven/data"),
            binder_path: PathBuf::from("/dev/binderfs"),
            binder_devices: vec![
                "binder".to_string(),
                "hwbinder".to_string(),
                "vndbinder".to_string(),
            ],
            render_nodes: vec![PathBuf::from("/dev/dri/renderD128")],
            wayland_socket: Some(PathBuf::from("/run/user/1000/wayland-0")),
            pulse_socket: Some(PathBuf::from("/run/user/1000/pulse/native")),
            cgroup_v2: true,
            host_egl_dirs: Vec::new(),
            uid: 1000,
            gid: 1000,
        }
    }

    #[test]
    fn the_config_names_android_init_as_the_entry_point() {
        let rendered = config().render();
        assert!(rendered.contains("lxc.init.cmd = /init"), "{rendered}");
        assert!(rendered.contains("lxc.uts.name = cookie"), "{rendered}");
    }

    #[test]
    fn the_rootfs_and_data_directories_are_wired_up() {
        let rendered = config().render();
        assert!(
            rendered.contains("lxc.rootfs.path = dir:/home/u/.local/share/cookie/oven/rootfs"),
            "{rendered}"
        );
        assert!(
            rendered.contains("/home/u/.local/share/cookie/oven/data data none bind"),
            "{rendered}"
        );
    }

    #[test]
    fn every_binder_device_is_bound_in() {
        let rendered = config().render();
        for name in ["binder", "hwbinder", "vndbinder"] {
            assert!(
                rendered.contains(&format!("/dev/binderfs/{name} dev/{name} none bind")),
                "{name} missing from:\n{rendered}"
            );
        }
    }

    #[test]
    fn devices_are_denied_before_any_are_allowed() {
        let rendered = config().render();
        let deny = rendered
            .find("lxc.cgroup2.devices.deny = a")
            .expect("a deny-all rule");
        let first_allow = rendered
            .find("lxc.cgroup2.devices.allow")
            .expect("an allow rule");
        assert!(
            deny < first_allow,
            "the deny-all must come first or it undoes the allowlist:\n{rendered}"
        );
    }

    #[test]
    fn the_gpu_is_passed_through_when_there_is_one() {
        let rendered = config().render();
        assert!(
            rendered.contains("/dev/dri/renderD128 dev/dri/renderD128 none bind"),
            "{rendered}"
        );
    }

    #[test]
    fn no_gpu_means_no_gpu_section() {
        let mut config = config();
        config.render_nodes.clear();
        let rendered = config.render();
        assert!(!rendered.contains("dev/dri"), "{rendered}");
        // And it still renders everything else.
        assert!(rendered.contains("lxc.init.cmd = /init"), "{rendered}");
    }

    #[test]
    fn no_wayland_socket_means_no_wayland_mount() {
        let mut config = config();
        config.wayland_socket = None;
        let rendered = config.render();
        assert!(!rendered.contains("wayland-0"), "{rendered}");
        assert!(!rendered.contains("WAYLAND_DISPLAY"), "{rendered}");
    }

    /// The display path, such as it is on the host: put the desktop's socket
    /// where the image's hardware composer looks for it.
    #[test]
    fn the_wayland_socket_lands_where_the_image_expects_it() {
        let rendered = config().render();
        assert!(
            rendered.contains("/run/user/1000/wayland-0 run/xdg/wayland-0 none rbind"),
            "{rendered}"
        );
        // And a tmpfs has to exist first or there is nothing to mount onto.
        let tmpfs = rendered
            .find("tmpfs run/xdg")
            .expect("a tmpfs for /run/xdg");
        let socket = rendered.find("run/xdg/wayland-0 none").expect("the socket");
        assert!(tmpfs < socket, "the tmpfs must come first:\n{rendered}");
    }

    #[test]
    fn the_composer_can_find_the_socket_through_the_usual_variables() {
        let rendered = config().render();
        assert!(
            rendered.contains("lxc.environment = XDG_RUNTIME_DIR=/run/xdg"),
            "{rendered}"
        );
        assert!(
            rendered.contains("lxc.environment = WAYLAND_DISPLAY=wayland-0"),
            "{rendered}"
        );
    }

    #[test]
    fn the_fence_device_is_passed_through_for_the_composer() {
        assert!(config().render().contains("dev/sw_sync"));
    }

    #[test]
    fn sound_is_optional() {
        let mut config = config();
        assert!(config.render().contains("pulse/native"));
        config.pulse_socket = None;
        assert!(!config.render().contains("pulse/native"));
    }

    #[test]
    fn android_supplies_its_own_confinement() {
        let rendered = config().render();
        // LXC's AppArmor profile and seccomp filter both get in Android's
        // way; Android has its own SELinux policy inside the image.
        assert!(
            rendered.contains("lxc.apparmor.profile = unconfined"),
            "{rendered}"
        );
        assert!(rendered.contains("lxc.seccomp.profile ="), "{rendered}");
        assert!(rendered.contains("lxc.autodev = 0"), "{rendered}");
    }

    #[test]
    fn the_config_starts_with_a_comment_saying_not_to_edit_it() {
        let rendered = config().render();
        assert!(rendered.starts_with("# Generated by cookie "), "{rendered}");
        assert!(rendered.contains("Do not edit"), "{rendered}");
    }

    #[test]
    fn rendering_is_deterministic() {
        assert_eq!(config().render(), config().render());
    }

    #[test]
    fn androids_init_keeps_the_capabilities_it_needs() {
        let rendered = config().render();
        // lxc.cap.keep is an allowlist: anything not named is dropped, and
        // Android's init mounts filesystems, makes nodes and sets the clock.
        assert!(rendered.contains("lxc.cap.keep = "), "{rendered}");
        for capability in ["sys_admin", "mknod", "sys_time", "net_admin", "sys_ptrace"] {
            assert!(
                rendered.contains(capability),
                "{capability} missing from:\n{rendered}"
            );
        }
    }

    #[test]
    fn the_kernel_filesystems_are_mounted() {
        assert!(config()
            .render()
            .contains("lxc.mount.auto = cgroup:ro sys:ro proc"));
    }

    /// With autodev off, a tmpfs has to exist on /dev before anything can be
    /// bound into it — this is what a read-only root used to make impossible.
    #[test]
    fn dev_is_a_tmpfs_before_anything_is_bound_into_it() {
        let rendered = config().render();
        let tmpfs = rendered
            .find("lxc.mount.entry = tmpfs dev tmpfs")
            .expect("a tmpfs on /dev");
        let binder = rendered.find("dev/binder none bind").expect("binder");
        let null = rendered.find("/dev/null dev/null").expect("null");
        assert!(tmpfs < binder, "the tmpfs must come first:\n{rendered}");
        assert!(tmpfs < null, "the tmpfs must come first:\n{rendered}");
    }

    #[test]
    fn the_basic_device_nodes_come_from_the_host() {
        let rendered = config().render();
        for node in ["null", "zero", "urandom", "ptmx"] {
            assert!(
                rendered.contains(&format!("/dev/{node} dev/{node} none bind")),
                "{node} missing from:\n{rendered}"
            );
        }
    }

    /// The allowlist key differs between cgroup hierarchies, and writing the
    /// wrong one means no allowlist at all rather than an error.
    #[test]
    fn the_device_allowlist_matches_the_hosts_cgroup_version() {
        let mut config = config();

        config.cgroup_v2 = true;
        let v2 = config.render();
        assert!(v2.contains("lxc.cgroup2.devices.deny = a"), "{v2}");
        assert!(!v2.contains("lxc.cgroup.devices"), "{v2}");

        config.cgroup_v2 = false;
        let v1 = config.render();
        assert!(v1.contains("lxc.cgroup.devices.deny = a"), "{v1}");
        assert!(!v1.contains("lxc.cgroup2.devices"), "{v1}");
    }

    #[test]
    fn host_egl_directories_are_passed_through_when_there_are_any() {
        let mut config = config();
        assert!(!config.render().contains("vendor/lib64/egl"));

        config.host_egl_dirs = vec![PathBuf::from("/vendor/lib64/egl")];
        assert!(config
            .render()
            .contains("/vendor/lib64/egl vendor/lib64/egl none bind"));
    }

    #[test]
    fn the_architecture_is_one_lxc_understands() {
        assert!(
            ["x86_64", "i686", "aarch64", "armv7l"].contains(&host_lxc_arch()),
            "unexpected arch {}",
            host_lxc_arch()
        );
    }
}
